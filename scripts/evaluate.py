"""Evaluate VADER (analyzer.nltk_layer) against star ratings and write docs/evaluation.md.

    pip install -r requirements-dev.txt
    python scripts/evaluate.py

Weak gold labels from stars: 1-2 -> negative, 3 -> neutral, 4-5 -> positive (a proxy for sentiment).
Predictions: VADER compound with the standard +/-0.05 thresholds.
Headline metric: macro-F1 (reviews skew positive, so accuracy overstates performance).
Sources: knowledge/eval-report-writer/*.md (scikit-learn metrics docs, VADER README).
"""
from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

from sklearn.metrics import accuracy_score, classification_report, cohen_kappa_score, confusion_matrix, f1_score  # noqa: E402

LABELS = ["negative", "neutral", "positive"]


def star_label(r: float) -> str:
    return "negative" if r <= 2 else "neutral" if r == 3 else "positive"


def bin5(c: float) -> int:
    """Compound -> 1..5 for an ordinal comparison with stars."""
    edges = [-0.6, -0.05, 0.05, 0.6]
    return 1 + sum(c > e for e in edges)


def main() -> int:
    from build_analysis import ensure_nltk_data
    ensure_nltk_data(ROOT / "nltk_data")
    from analyzer import nltk_layer as nl
    from nltk.sentiment.vader import SentimentIntensityAnalyzer

    reviews = [json.loads(l) for l in open(ROOT / "data" / "sample" / "reviews.jsonl", encoding="utf-8")]
    y_true = [star_label(r["rating"]) for r in reviews]
    comp = [nl.compound(r["text"]) for r in reviews]
    y_pred = [nl.label(c) for c in comp]
    plain = SentimentIntensityAnalyzer()  # stock VADER lexicon, no domain additions
    comp_plain = [round(plain.polarity_scores(r["text"])["compound"], 4) for r in reviews]
    y_plain = [nl.label(c) for c in comp_plain]

    rep = classification_report(y_true, y_pred, labels=LABELS, output_dict=True, zero_division=0)
    cm = confusion_matrix(y_true, y_pred, labels=LABELS)
    cmn = confusion_matrix(y_true, y_pred, labels=LABELS, normalize="true")
    macro = f1_score(y_true, y_pred, labels=LABELS, average="macro", zero_division=0)
    macro_plain = f1_score(y_true, y_plain, labels=LABELS, average="macro", zero_division=0)
    acc = accuracy_score(y_true, y_pred)
    kappa = cohen_kappa_score([int(r["rating"]) for r in reviews], [bin5(c) for c in comp], weights="quadratic")
    # Binary view (drop 3-star and VADER-neutral): how well does VADER separate praise from complaints?
    bin_idx = [i for i, (t, p) in enumerate(zip(y_true, y_pred)) if t != "neutral" and p != "neutral"]
    bin_f1 = f1_score([y_true[i] for i in bin_idx], [y_pred[i] for i in bin_idx], average="macro")
    stars = Counter(int(r["rating"]) for r in reviews)

    def examples(cond, n=5):
        idx = [i for i, r in enumerate(reviews) if cond(r, comp[i]) and 40 <= len(r["text"]) <= 260]
        idx.sort(key=lambda i: (-abs(comp[i]), reviews[i]["parent_asin"], reviews[i]["timestamp"]))
        return [(reviews[i]["rating"], comp[i], reviews[i]["text"].replace("|", "/").replace("\n", " ")) for i in idx[:n]]

    five_neg = examples(lambda r, c: r["rating"] == 5 and c <= -0.05)
    one_pos = examples(lambda r, c: r["rating"] == 1 and c >= 0.05)

    pct = lambda x: f"{100 * x:.1f}%"
    lines = [
        "# Evaluation: VADER sentiment vs. star ratings",
        "",
        "Generated by `python scripts/evaluate.py` from `data/sample/reviews.jsonl` "
        f"({len(reviews):,} All_Beauty reviews). Re-run it after changing `analyzer/nltk_layer.py`.",
        "",
        "## Setup",
        "- **Prediction:** NLTK 3.9.4 VADER `compound` on the review text, through `analyzer/nltk_layer.py` "
        "(the same code the build and the browser run). Labels: positive >= 0.05, negative <= -0.05, otherwise neutral "
        "(VADER README thresholds).",
        "- **Weak gold labels from stars:** 1-2 stars = negative, 3 = neutral, 4-5 = positive. Stars are a *proxy* for "
        "the sentiment of the text, not a human sentiment annotation.",
        "- **Headline metric: macro-F1**, because the classes are imbalanced: "
        + ", ".join(f"{k} star {stars.get(k, 0):,}" for k in range(1, 6)) + ".",
        "",
        "## Results",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| **Macro-F1 (3 classes)** | **{macro:.3f}** |",
        f"| Accuracy | {acc:.3f} |",
        f"| Weighted-F1 | {rep['weighted avg']['f1-score']:.3f} |",
        f"| Quadratic Cohen's kappa, stars (1-5) vs. compound binned into 5 | {kappa:.3f} |",
        f"| Macro-F1, binary (positive vs. negative only, {len(bin_idx):,} reviews) | {bin_f1:.3f} |",
        f"| Macro-F1 with the stock VADER lexicon (no domain words) | {macro_plain:.3f} |",
        "",
        "Per class:",
        "",
        "| Class | Precision | Recall | F1 | Support |",
        "|---|---|---|---|---|",
    ]
    for lab in LABELS:
        r = rep[lab]
        lines.append(f"| {lab} | {r['precision']:.3f} | {r['recall']:.3f} | {r['f1-score']:.3f} | {int(r['support']):,} |")
    lines += [
        "",
        "Confusion matrix (rows = star label, columns = VADER label; counts and row-normalized share):",
        "",
        "| true \\ predicted | negative | neutral | positive |",
        "|---|---|---|---|",
    ]
    for i, lab in enumerate(LABELS):
        lines.append(f"| **{lab}** | " + " | ".join(f"{cm[i][j]:,} ({pct(cmn[i][j])})" for j in range(3)) + " |")
    lines += [
        "",
        "## Reading the numbers",
        f"- VADER is strong on clear praise: positive recall is {pct(rep['positive']['recall'])}.",
        f"- It is weaker on complaints: only {pct(rep['negative']['recall'])} of 1-2 star reviews are scored negative. "
        "Many complaints are factual descriptions of a defect or a return, with few lexicon words.",
        f"- The neutral class is the hardest (F1 {rep['neutral']['f1-score']:.3f}): 3-star reviews are usually mixed "
        "(\"nice color, but it chips\"), and VADER sums them to a clearly positive or negative compound.",
        f"- The small domain lexicon in `nltk_layer.DOMAIN_LEXICON` (e.g. flimsy, greasy, sticky, overpriced; never overriding "
        f"VADER's own ratings) changes macro-F1 from {macro_plain:.3f} to {macro:.3f}.",
        "",
        "## Error analysis",
        "",
        "5-star reviews scored negative (strongest first):",
        "",
        "| Stars | Compound | Text |",
        "|---|---|---|",
    ] + [f"| {s:.0f} | {c:+.4f} | {t} |" for s, c, t in five_neg] + [
        "",
        "1-star reviews scored positive:",
        "",
        "| Stars | Compound | Text |",
        "|---|---|---|",
    ] + [f"| {s:.0f} | {c:+.4f} | {t} |" for s, c, t in one_pos] + [
        "",
        "Typical causes: negative words describing the *problem the product solved* (\"my dying, dull and unimpressive looking hair\"), "
        "sarcasm and disappointment phrased politely (\"I wanted to love it\"), domain phrases VADER does not know "
        "(\"runs small\", \"broke me out\"), and reviews where the stars disagree with the text.",
        "",
        "## NLP correctness review (spaCy + NLTK)",
        "- **Shared code:** the playground imports the same `nltk_layer.py`. The Playwright test "
        "`tests/e2e/test_site.py::test_playground_matches_build_scores` checks that Pyodide 314.0.8 returns the same "
        "compound as the build (|diff| <= 1e-4) for the examples in `site/data/nltk_examples.json`.",
        "- **Stopwords:** removed only for FreqDist and collocations, never before VADER. Negations stay in the vocabulary, "
        "so complaint phrases such as \"not worth\", \"not work\" and \"stop work\" appear among the negative collocations.",
        "- **Collocations:** bigrams are counted inside sentences (`from_documents`), with a frequency filter "
        "(5 for the category, 3 per product) and the likelihood-ratio measure, so rare pairs do not dominate as they do with PMI.",
        "- **Aspects:** the spaCy rules (amod, acomp + nsubj, opinion verb + dobj, conj, neg) are checked on golden sentences "
        "in `tests/test_spacy_layer.py`. Known gaps: the small model mislabels some entities (e.g. \"polish\" as NORP, "
        "\"Norelco\" as GPE), and adjectives that describe a type rather than an opinion are only partly filtered "
        "(`NON_OPINION_ADJ`).",
        "- **Not done:** a hand-labeled set of about 100 aspect-opinion triples to measure extraction precision (and "
        "inter-annotator kappa). That needs human annotators, so it is listed as future work.",
        "",
        "## Limitations",
        "- VADER is a lexicon and rule model \"specifically attuned to sentiments expressed in social media\" (VADER README). "
        "It handles negation, boosters, capitals, punctuation and emoji, but not sarcasm or most domain-specific phrasing.",
        "- Star ratings are a weak proxy for the sentiment of the text.",
        "- \"Sales\" metrics are proxies (rating counts and review velocity), not revenue. No simulated sales data is used.",
        "- The sample (200 products, up to 60 reviews each) over-represents popular products by design.",
        "- spaCy analysis runs only at build time. Live analysis in the browser uses NLTK alone.",
        "- Amazon Reviews 2023 declares no license, so it is used for academic, non-commercial work only "
        "(Hou et al. 2024, arXiv:2403.03952).",
        "",
        "## References",
        "- Hutto, C.J. & Gilbert, E.E. (2014). VADER: A Parsimonious Rule-based Model for Sentiment Analysis of Social "
        "Media Text. ICWSM-14. https://github.com/cjhutto/vaderSentiment",
        "- Bird, S., Klein, E., & Loper, E. (2009). Natural Language Processing with Python. O'Reilly. https://www.nltk.org/",
        "- Honnibal, M., Montani, I., Van Landeghem, S., & Boyd, A. (2020). spaCy: Industrial-strength Natural Language "
        "Processing in Python. doi:10.5281/zenodo.1212303",
        "- Hou, Y., Li, J., He, Z., Yan, A., Chen, X., & McAuley, J. (2024). Bridging Language and Items for Retrieval and "
        "Recommendation. arXiv:2403.03952",
        "- scikit-learn metrics: https://scikit-learn.org/stable/modules/generated/sklearn.metrics.classification_report.html",
        "",
    ]
    out = ROOT / "docs" / "evaluation.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"macro-F1 {macro:.3f} (stock lexicon {macro_plain:.3f}), accuracy {acc:.3f}, kappa {kappa:.3f}, "
          f"binary macro-F1 {bin_f1:.3f} -> {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
